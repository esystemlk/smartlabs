"""Trace public/logo.png into vector paths (one per logo part) -> src/app/(home)/logo-paths.ts
Each part's outline is checked against the original pixels (IoU) so the vector logo matches the PNG."""
import json, numpy as np
from PIL import Image
from scipy import ndimage
from skimage import measure, draw

UP = 8
src = np.asarray(Image.open('public/logo.png').convert('RGBA')).astype(np.float32)
alpha = src[..., 3] / 255
lab, _ = ndimage.label(alpha > 60 / 255)
X0, Y0 = 13, 131                     # logo content origin (paths are relative to this)
PARTS = {'S': 2, 'M': 3, 'Aarch': 1, 'R': 4, 'T': 5, 'dot': 6, 'lineL': 11, 'lineR': 12, 'L': 8, 'A2': 7, 'B': 9, 'S2': 10}
out, report = {}, []
for name, cid in PARTS.items():
    region = ndimage.binary_dilation(lab == cid, iterations=2)
    a = alpha * region
    ys, xs = np.where(region); y0, y1, x0, x1 = ys.min() - 2, ys.max() + 3, xs.min() - 2, xs.max() + 3
    crop = a[y0:y1, x0:x1]
    big = np.asarray(Image.fromarray((crop * 255).astype(np.uint8)).resize(((x1 - x0) * UP, (y1 - y0) * UP), Image.BICUBIC)).astype(np.float32) / 255
    big = ndimage.gaussian_filter(big, 1.2)
    contours = measure.find_contours(np.pad(big, 1), 0.5)
    d, polys = [], []
    for c in contours:
        if len(c) < 8: continue
        c = measure.approximate_polygon(c - 1, tolerance=0.6)
        pts = [(x0 - X0 + p[1] / UP, y0 - Y0 + p[0] / UP) for p in c]
        polys.append(c)
        d.append('M' + 'L'.join(f'{x:.2f} {y:.2f}' for x, y in pts) + 'Z')
    out[name] = ' '.join(d)
    # accuracy check: rasterise the traced outline (even-odd) vs the original thresholded upscale
    ras = np.zeros(big.shape, bool)
    for c in polys:
        rr, cc = draw.polygon(c[:, 0], c[:, 1], big.shape); ras[rr, cc] ^= True
    ref = big > 0.5
    iou = (ras & ref).sum() / max(1, (ras | ref).sum())
    report.append(f'{name}: {iou:.3f}')
open('src/app/(home)/logo-paths.ts', 'w').write(
    '// Generated by design/logo-loop/trace.py from public/logo.png (do not edit by hand).\n'
    '// Coordinates are in logo pixels, origin at the top-left of the logo artwork (viewBox 0 0 644 112).\n'
    f'export const LOGO_PATHS = {json.dumps(out, indent=2)} as const;\n')
print(' | '.join(report))
print('total path chars', sum(len(v) for v in out.values()))
